CREATE TABLE T_FIN_USUARIO (
    id_usuario NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_usuario VARCHAR2(100) NOT NULL,
    ds_email   VARCHAR2(100) NOT NULL,
    ds_senha   VARCHAR2(255) NOT NULL,
    ds_cep     VARCHAR2(8) NOT NULL,
    CONSTRAINT pk_fin_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_fin_usuario_email UNIQUE (ds_email)
);

CREATE TABLE T_FIN_RECEITA (
    id_receita NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario NUMBER NOT NULL,
    vl_receita NUMBER(15,2) NOT NULL,
    dt_receita DATE NOT NULL,
    ds_receita VARCHAR2(255) NOT NULL,
    CONSTRAINT pk_fin_receita PRIMARY KEY (id_receita),
    CONSTRAINT fk_fin_receita_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);

CREATE TABLE T_FIN_DESPESA (
    id_despesa   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario   NUMBER NOT NULL,
    vl_despesa   NUMBER(15,2) NOT NULL,
    dt_despesa   DATE NOT NULL,
    ds_despesa   VARCHAR2(255) NOT NULL,
    ds_categoria VARCHAR2(30) DEFAULT 'OUTROS' NOT NULL,
    CONSTRAINT pk_fin_despesa PRIMARY KEY (id_despesa),
    CONSTRAINT fk_fin_despesa_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT ck_fin_despesa_categoria CHECK (ds_categoria IN
        ('ALIMENTACAO','TRANSPORTE','MORADIA','LAZER','SAUDE','EDUCACAO','OUTROS'))
);

CREATE TABLE T_FIN_DIVIDA (
    id_divida     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    NUMBER NOT NULL,
    vl_divida     NUMBER(15,2) NOT NULL,
    dt_vencimento DATE NOT NULL,
    ds_divida     VARCHAR2(255) NOT NULL,
    CONSTRAINT pk_fin_divida PRIMARY KEY (id_divida),
    CONSTRAINT fk_fin_divida_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);

CREATE TABLE T_FIN_METAS (
    id_meta       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    NUMBER NOT NULL,
    vl_alvo       NUMBER(15,2) NOT NULL,
    dt_limite     DATE NOT NULL,
    ds_meta       VARCHAR2(100) DEFAULT 'Meta financeira' NOT NULL,
    vl_acumulado  NUMBER(15,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_fin_metas PRIMARY KEY (id_meta),
    CONSTRAINT fk_fin_metas_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);

CREATE TABLE T_FIN_CONTA (
    id_conta      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    NUMBER NOT NULL,
    nm_banco      VARCHAR2(100) NOT NULL,
    nr_agencia    VARCHAR2(10) NOT NULL,
    nr_conta      VARCHAR2(20) NOT NULL,
    ds_tipo_conta VARCHAR2(20) NOT NULL,
    vl_saldo      NUMBER(15,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_fin_conta PRIMARY KEY (id_conta),
    CONSTRAINT fk_fin_conta_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT ck_fin_conta_tipo CHECK (UPPER(ds_tipo_conta) IN ('CORRENTE','POUPANCA'))
);

CREATE TABLE T_FIN_CAT_INVEST (
    id_cat_invest NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nm_categoria  VARCHAR2(50) NOT NULL,
    ds_risco      VARCHAR2(30) NOT NULL,
    CONSTRAINT pk_fin_cat_invest PRIMARY KEY (id_cat_invest)
);

CREATE TABLE T_FIN_INVESTIMENTO (
    id_invest     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    NUMBER NOT NULL,
    id_cat_invest NUMBER NOT NULL,
    vl_investido  NUMBER(15,2) NOT NULL,
    dt_invest     DATE NOT NULL,
    CONSTRAINT pk_fin_investimento PRIMARY KEY (id_invest),
    CONSTRAINT fk_fin_invest_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT fk_fin_invest_categoria FOREIGN KEY (id_cat_invest) REFERENCES T_FIN_CAT_INVEST(id_cat_invest)
);

CREATE TABLE T_FIN_ORCAMENTO (
    id_orcamento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario   NUMBER NOT NULL,
    ds_categoria VARCHAR2(30) NOT NULL,
    vl_limite    NUMBER(15,2) NOT NULL,
    CONSTRAINT pk_fin_orcamento PRIMARY KEY (id_orcamento),
    CONSTRAINT fk_fin_orcamento_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT uk_fin_orcamento_categoria UNIQUE (id_usuario, ds_categoria),
    CONSTRAINT ck_fin_orcamento_categoria CHECK (ds_categoria IN
        ('ALIMENTACAO','TRANSPORTE','MORADIA','LAZER','SAUDE','EDUCACAO','OUTROS'))
);

CREATE TABLE T_FIN_LOG_CHAT (
    id_interacao  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    NUMBER NOT NULL,
    dh_inicio     TIMESTAMP NOT NULL,
    dh_fim        TIMESTAMP NOT NULL,
    vl_latencia   NUMBER(10,3) NOT NULL,
    st_resolucao  VARCHAR2(20) NOT NULL,
    ds_sentimento VARCHAR2(20) NOT NULL,
    nr_csat       NUMBER(1) NOT NULL,
    CONSTRAINT pk_fin_log_chat PRIMARY KEY (id_interacao),
    CONSTRAINT fk_fin_log_chat_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);
