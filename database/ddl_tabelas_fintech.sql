-- Reune, em um unico script, tudo o que o Fintech definiu ao longo do ano:
--   Fase 3 (Modelagem de Dados): T_FIN_USUARIO, RECEITA, DESPESA, DIVIDA,
--                                METAS, CAT_INVEST, INVESTIMENTO e LOG_CHAT.
--   Fase 6 (Comandos DML):       T_FIN_CONTA.
--   Fase 7 (este projeto), evolucao do modelo para atender as user stories da Fase 1:
--     * T_FIN_DESPESA.ds_categoria   (US01: categoria da despesa)
--     * T_FIN_METAS.ds_meta e vl_acumulado (progresso da meta)
--     * T_FIN_ORCAMENTO              (US03: limite de gastos por categoria)
--
-- Entidade Java x tabela:
--   Usuario -> T_FIN_USUARIO          Receita -> T_FIN_RECEITA
--   Despesa -> T_FIN_DESPESA          Divida  -> T_FIN_DIVIDA
--   Meta    -> T_FIN_METAS            Conta   -> T_FIN_CONTA
--   CategoriaInvestimento -> T_FIN_CAT_INVEST   Investimento -> T_FIN_INVESTIMENTO
--   Orcamento -> T_FIN_ORCAMENTO      LogChat -> T_FIN_LOG_CHAT
--
-- Como rodar: no SQL Developer, conectado com o usuario RM da FIAP, executar o
-- script inteiro (F5). Se uma tabela ja existir, o Oracle responde ORA-00955
-- naquele CREATE e segue; nao e problema.
-- Quem ja tem o esquema da Fase 6 deve rodar ddl_evolucao_fase7.sql (so o que falta).
