-- Esquema do SpendWise para PostgreSQL (Supabase).
-- Equivale ao database/ddl_tabelas_fintech.sql do Oracle, com os tipos do Postgres.
-- Roda sozinho a cada subida do backend com o perfil "supabase"; CREATE ... IF NOT EXISTS
-- torna a execucao segura: o que ja existe nao e alterado.
-- Colunas acrescentadas depois da criacao inicial entram por ALTER TABLE ... IF NOT EXISTS (fim do arquivo).

CREATE TABLE IF NOT EXISTS T_FIN_USUARIO (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nm_usuario VARCHAR(100) NOT NULL,
    ds_email   VARCHAR(100) NOT NULL,
    ds_senha   VARCHAR(255) NOT NULL,
    ds_cep     VARCHAR(8) NOT NULL,
    ds_papel   VARCHAR(10) DEFAULT 'USUARIO' NOT NULL,
    CONSTRAINT pk_fin_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uk_fin_usuario_email UNIQUE (ds_email)
);

CREATE TABLE IF NOT EXISTS T_FIN_RECEITA (
    id_receita BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario BIGINT NOT NULL,
    vl_receita NUMERIC(15,2) NOT NULL,
    dt_receita DATE NOT NULL,
    ds_receita VARCHAR(255) NOT NULL,
    CONSTRAINT pk_fin_receita PRIMARY KEY (id_receita),
    CONSTRAINT fk_fin_receita_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);

CREATE TABLE IF NOT EXISTS T_FIN_DESPESA (
    id_despesa   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario   BIGINT NOT NULL,
    vl_despesa   NUMERIC(15,2) NOT NULL,
    dt_despesa   DATE NOT NULL,
    ds_despesa   VARCHAR(255) NOT NULL,
    ds_categoria VARCHAR(30) DEFAULT 'OUTROS' NOT NULL,
    CONSTRAINT pk_fin_despesa PRIMARY KEY (id_despesa),
    CONSTRAINT fk_fin_despesa_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT ck_fin_despesa_categoria CHECK (ds_categoria IN
        ('ALIMENTACAO','TRANSPORTE','MORADIA','LAZER','SAUDE','EDUCACAO','OUTROS'))
);

CREATE TABLE IF NOT EXISTS T_FIN_DIVIDA (
    id_divida     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    BIGINT NOT NULL,
    vl_divida     NUMERIC(15,2) NOT NULL,
    dt_vencimento DATE NOT NULL,
    ds_divida     VARCHAR(255) NOT NULL,
    CONSTRAINT pk_fin_divida PRIMARY KEY (id_divida),
    CONSTRAINT fk_fin_divida_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);

CREATE TABLE IF NOT EXISTS T_FIN_METAS (
    id_meta       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    BIGINT NOT NULL,
    vl_alvo       NUMERIC(15,2) NOT NULL,
    dt_limite     DATE NOT NULL,
    ds_meta       VARCHAR(100) DEFAULT 'Meta financeira' NOT NULL,
    vl_acumulado  NUMERIC(15,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_fin_metas PRIMARY KEY (id_meta),
    CONSTRAINT fk_fin_metas_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);

CREATE TABLE IF NOT EXISTS T_FIN_CONTA (
    id_conta      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    BIGINT NOT NULL,
    nm_banco      VARCHAR(100) NOT NULL,
    nr_agencia    VARCHAR(10) NOT NULL,
    nr_conta      VARCHAR(20) NOT NULL,
    ds_tipo_conta VARCHAR(20) NOT NULL,
    vl_saldo      NUMERIC(15,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_fin_conta PRIMARY KEY (id_conta),
    CONSTRAINT fk_fin_conta_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT ck_fin_conta_tipo CHECK (UPPER(ds_tipo_conta) IN ('CORRENTE','POUPANCA'))
);

CREATE TABLE IF NOT EXISTS T_FIN_CAT_INVEST (
    id_cat_invest BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nm_categoria  VARCHAR(50) NOT NULL,
    ds_risco      VARCHAR(30) NOT NULL,
    CONSTRAINT pk_fin_cat_invest PRIMARY KEY (id_cat_invest)
);

CREATE TABLE IF NOT EXISTS T_FIN_INVESTIMENTO (
    id_invest     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    BIGINT NOT NULL,
    id_cat_invest BIGINT NOT NULL,
    vl_investido  NUMERIC(15,2) NOT NULL,
    dt_invest     DATE NOT NULL,
    CONSTRAINT pk_fin_investimento PRIMARY KEY (id_invest),
    CONSTRAINT fk_fin_invest_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT fk_fin_invest_categoria FOREIGN KEY (id_cat_invest) REFERENCES T_FIN_CAT_INVEST(id_cat_invest)
);

CREATE TABLE IF NOT EXISTS T_FIN_ORCAMENTO (
    id_orcamento BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario   BIGINT NOT NULL,
    ds_categoria VARCHAR(30) NOT NULL,
    vl_limite    NUMERIC(15,2) NOT NULL,
    CONSTRAINT pk_fin_orcamento PRIMARY KEY (id_orcamento),
    CONSTRAINT fk_fin_orcamento_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario),
    CONSTRAINT uk_fin_orcamento_categoria UNIQUE (id_usuario, ds_categoria),
    CONSTRAINT ck_fin_orcamento_categoria CHECK (ds_categoria IN
        ('ALIMENTACAO','TRANSPORTE','MORADIA','LAZER','SAUDE','EDUCACAO','OUTROS'))
);

CREATE TABLE IF NOT EXISTS T_FIN_LOG_CHAT (
    id_interacao  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    BIGINT NOT NULL,
    dh_inicio     TIMESTAMP NOT NULL,
    dh_fim        TIMESTAMP NOT NULL,
    vl_latencia   NUMERIC(10,3) NOT NULL,
    st_resolucao  VARCHAR(20) NOT NULL,
    ds_sentimento VARCHAR(20) NOT NULL,
    nr_csat       SMALLINT NOT NULL,
    CONSTRAINT pk_fin_log_chat PRIMARY KEY (id_interacao),
    CONSTRAINT fk_fin_log_chat_usuario FOREIGN KEY (id_usuario) REFERENCES T_FIN_USUARIO(id_usuario)
);

-- Papel do usuario (USUARIO ou MASTER). Para bancos criados antes desta coluna existir.
ALTER TABLE T_FIN_USUARIO ADD COLUMN IF NOT EXISTS ds_papel VARCHAR(10) DEFAULT 'USUARIO' NOT NULL;
